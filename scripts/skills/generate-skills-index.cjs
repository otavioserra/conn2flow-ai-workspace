// REQ-088 / ARCH-018: deterministic catalog of the canonical skills in .gemini/skills/index.md.
//
//   node scripts/skills/generate-skills-index.cjs           writes the index
//   node scripts/skills/generate-skills-index.cjs --check   exit 1 when the index is stale; writes nothing
//   node scripts/skills/generate-skills-index.cjs --budget-report [--text]   OVER/NEAR Skill Budget report; writes nothing
//
// Output depends only on the files in .gemini/skills and on scripts/skills/translated.json:
// no timestamps, LF line endings, sorted entries. Line counts ignore CRLF/LF differences.
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '../..');
const skillsDir = path.join(root, '.gemini/skills');
const indexFile = path.join(skillsDir, 'index.md');
const registry = JSON.parse(fs.readFileSync(path.join(__dirname, 'translated.json'), 'utf8'));

// Governance skills whose names start with c2f- (the remaining c2f-* are core skills).
const GOVERNANCE_C2F = new Set(['c2f-mdd-indexing-and-handoffs', 'c2f-multilingual-skills-governance']);
// Suggested review ceiling in lines (Skill Budget). NEAR from 80 %. Automated enforcement is ARCH-018 Phase 4.
const BUDGET = { persona: 200, core: 300, governance: 200 };
const GROUPS = [
  ['persona', 'Personas (`c2f-persona-*`)'],
  ['core', 'Core skills (`c2f-*`)'],
  ['governance', 'Governance and MDD workflow skills'],
];

const text = (file) => fs.readFileSync(file, 'utf8').replace(/^﻿/, '').replace(/\r\n/g, '\n');
const lines = (content) => content.split('\n').length - (content.endsWith('\n') ? 1 : 0);
const bytes = (content) => Buffer.byteLength(content, 'utf8');
const category = (name) => (name.startsWith('c2f-persona-') ? 'persona'
  : name.startsWith('c2f-') && !GOVERNANCE_C2F.has(name) ? 'core' : 'governance');
const cell = (value) => String(value).replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();

function frontmatter(content) {
  const match = content.match(/^---\n([\s\S]*?)\n---/);
  const field = (key) => {
    const line = match && match[1].split('\n').find((l) => l.startsWith(`${key}:`));
    return line ? line.slice(key.length + 1).trim().replace(/^"(.*)"$/, '$1') : '';
  };
  return { name: field('name'), invocable: field('user-invocable') === 'true' };
}

function walk(dir, prefix) {
  return fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => (a.name < b.name ? -1 : 1)).flatMap((entry) => {
    const file = path.join(dir, entry.name);
    if (entry.isSymbolicLink()) throw new Error(`Refusing linked subskill: ${file}`);
    return entry.isDirectory() ? walk(file, `${prefix}/${entry.name}`) : [`${prefix}/${entry.name}`];
  });
}

const skills = fs.readdirSync(skillsDir, { withFileTypes: true })
  .filter((e) => e.isDirectory() && fs.existsSync(path.join(skillsDir, e.name, 'SKILL.md')))
  .map((e) => e.name).sort()
  .map((name) => {
    const content = text(path.join(skillsDir, name, 'SKILL.md'));
    const meta = frontmatter(content);
    if (meta.name !== name) throw new Error(`Frontmatter name differs from folder: ${name} (${meta.name || 'missing'})`);
    const subDir = path.join(skillsDir, name, 'subskills');
    const subskills = fs.existsSync(subDir) ? walk(subDir, 'subskills').map((rel) => {
      const body = text(path.join(skillsDir, name, ...rel.split('/')));
      return { rel, lines: lines(body), bytes: bytes(body) };
    }) : [];
    const kind = category(name);
    const count = lines(content);
    const budget = BUDGET[kind];
    const state = count > budget ? 'OVER' : count >= Math.ceil(budget * 0.8) ? 'NEAR' : 'OK';
    const translations = Object.keys(registry).sort().filter((lang) => registry[lang][name])
      .map((lang) => `${lang} ${registry[lang][name].translated_at}`);
    return { name, kind, lines: count, bytes: bytes(content), budget, state, subskills, invocable: meta.invocable, translations };
  });

const out = [
  '# Skills Index — canonical catalog',
  '',
  '<!-- Generated by scripts/skills/generate-skills-index.cjs. Do not edit by hand; run the script. -->',
  '',
  `Canonical source: \`.gemini/skills/\`. Total: **${skills.length} skills** — ` +
    GROUPS.map(([kind]) => `${skills.filter((s) => s.kind === kind).length} ${kind}`).join(', ') +
    `; ${skills.reduce((n, s) => n + s.subskills.length, 0)} subskill file(s).`,
  '',
  `Skill Budget (suggested review ceiling in lines): persona ${BUDGET.persona}, core ${BUDGET.core}, governance ${BUDGET.governance}. ` +
    '`NEAR` starts at 80 %. Over budget: condense or move recipes to `<skill>/subskills/` (see `c2f-persona-optimizer`).',
  '',
];
for (const [kind, title] of GROUPS) {
  const group = skills.filter((s) => s.kind === kind);
  out.push(`## ${title} — ${group.length}`, '', '| Skill | Lines | Bytes | Budget | State | Invocable | Subskills | Translations |',
    '| --- | ---: | ---: | ---: | --- | --- | --- | --- |');
  for (const s of group) {
    const subs = s.subskills.map((x) => `[${x.rel.replace(/^subskills\//, '')}](${s.name}/${x.rel}) (${x.lines})`).join('<br>') || '—';
    out.push(`| [\`${s.name}\`](${s.name}/SKILL.md) | ${s.lines} | ${s.bytes} | ${s.budget} | ${s.state} | ${s.invocable ? 'yes' : 'no'} | ${cell(subs)} | ${s.translations.join(', ') || '—'} |`);
  }
  out.push('');
}
const attention = skills.filter((s) => s.state !== 'OK');
out.push('## Budget attention', '');
if (attention.length) for (const s of attention) out.push(`- \`${s.name}\`: ${s.lines}/${s.budget} lines (${s.state})`);
else out.push('- None.');
const rendered = `${out.join('\n')}\n`;

if (process.argv.includes('--budget-report')) {
  // REQ-091 (ARCH-018 Phase 4): read-only Skill Budget report for the Anti-Bloat Tribunal. Writes nothing.
  const pick = (state) => skills.filter((s) => s.state === state)
    .map((s) => ({ skill: s.name, kind: s.kind, lines: s.lines, budget: s.budget, ratio: Math.round((s.lines / s.budget) * 100) / 100 }))
    .sort((a, b) => b.ratio - a.ratio || (a.skill < b.skill ? -1 : 1));
  const report = { status: 'REPORT', skills: skills.length, budget: BUDGET, near_threshold: 0.8,
    counts: { OVER: pick('OVER').length, NEAR: pick('NEAR').length, OK: skills.filter((s) => s.state === 'OK').length },
    over: pick('OVER'), near: pick('NEAR') };
  if (process.argv.includes('--text')) {
    console.log(`Skill Budget — ${skills.length} skills: ${report.counts.OVER} OVER, ${report.counts.NEAR} NEAR, ${report.counts.OK} OK`);
    for (const [state, list] of [['OVER', report.over], ['NEAR', report.near]]) {
      for (const s of list) console.log(`  ${state.padEnd(4)} ${s.skill} ${s.lines}/${s.budget} (${s.kind})`);
    }
  } else {
    console.log(JSON.stringify(report));
  }
} else if (process.argv.includes('--check')) {
  const current = fs.existsSync(indexFile) ? text(indexFile) : '';
  const fresh = current === rendered;
  console.log(JSON.stringify({ status: fresh ? 'PASS' : 'STALE', skills: skills.length, index: path.relative(root, indexFile).replace(/\\/g, '/') }));
  if (!fresh) process.exitCode = 1;
} else {
  fs.writeFileSync(indexFile, rendered);
  console.log(JSON.stringify({ status: 'WRITTEN', skills: skills.length, attention: attention.map((s) => s.name) }));
}
